package mcp_test

import (
	"context"
	"fmt"
	"io"
	"net/http"
	"os"
	"regexp"
	"strings"
	"testing"

	factorymcp "github.com/KaaS-team/factory/internal/mcp"
)

const transcriptFile = "../../docs/demo/mcp-transcript.md"

// TestTranscriptIsCurrent replays an MCP session over HTTP against the real server and handler,
// with the OAuth guard on, and compares it to docs/demo/mcp-transcript.md. UPDATE_GOLDEN=1 rewrites it.
func TestTranscriptIsCurrent(t *testing.T) {
	ctl := newFake()
	h := factorymcp.Handlers{
		Version: func(context.Context) (string, error) { return "0.0.0-dev", nil },
		Packs:   func(context.Context) (string, error) { return "no packs pinned\n", nil },
	}
	handler, err := factorymcp.AuthHandler(factorymcp.NewServer(ctl, h), factorymcp.AuthConfig{
		Identity: fakeIdentity{}, Resource: "https://factory.example/mcp", AuthorizationServers: []string{"https://idp.example"},
		ReadOnly: factorymcp.NewServer(ctl, factorymcp.Handlers{Version: h.Version, Packs: h.Packs, ReadOnly: true}),
	})
	if err != nil {
		t.Fatal(err)
	}
	ts := newTS(t, handler)
	var out strings.Builder
	out.WriteString("# MCP transcript\n\nGenerated by `TestTranscriptIsCurrent` in `internal/mcp`. It drives the real MCP server and\nthe OAuth guard over HTTP. The control plane and the version and packs handlers are fakes, because\n`factory mcp` opens a live tracker. The token `admin` stands for a valid OIDC bearer token.\n\n")
	session := ""
	step := func(title, auth, body string) {
		req, _ := http.NewRequestWithContext(t.Context(), http.MethodPost, ts+"/mcp", strings.NewReader(body))
		req.Header.Set("Content-Type", "application/json")
		req.Header.Set("Accept", "application/json, text/event-stream")
		if auth != "" {
			req.Header.Set("Authorization", auth)
		}
		if session != "" {
			req.Header.Set("Mcp-Session-Id", session)
		}
		res, err := http.DefaultClient.Do(req)
		if err != nil {
			t.Fatal(err)
		}
		b, _ := io.ReadAll(res.Body)
		_ = res.Body.Close()
		if s := res.Header.Get("Mcp-Session-Id"); s != "" {
			session = s
		}
		resp := regexp.MustCompile(`(?m)^(event: message\n)?data: `).ReplaceAllString(strings.TrimSpace(string(b)), "")
		resp = regexp.MustCompile(`\n+`).ReplaceAllString(resp, "\n")
		fmt.Fprintf(&out, "## %s\n\nRequest:\n\n```\nPOST /mcp\nAuthorization: %s\n%s\n```\n\nResponse: %d", title, redact(auth), body, res.StatusCode)
		if w := res.Header.Get("WWW-Authenticate"); w != "" {
			fmt.Fprintf(&out, "\nWWW-Authenticate: %s", w)
		}
		fmt.Fprintf(&out, "\n\n```\n%s\n```\n\n", resp)
	}
	step("No token", "", initBody)
	step("Initialize", "Bearer admin", initBody)
	step("List tools", "Bearer admin", `{"jsonrpc":"2.0","id":2,"method":"tools/list"}`)
	step("Call version", "Bearer admin", `{"jsonrpc":"2.0","id":3,"method":"tools/call","params":{"name":"version","arguments":{}}}`)
	step("Call packs", "Bearer admin", `{"jsonrpc":"2.0","id":4,"method":"tools/call","params":{"name":"packs","arguments":{}}}`)
	step("Call status", "Bearer admin", `{"jsonrpc":"2.0","id":5,"method":"tools/call","params":{"name":"status","arguments":{}}}`)
	got := out.String()
	if os.Getenv("UPDATE_GOLDEN") != "" {
		if err := os.WriteFile(transcriptFile, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(transcriptFile)
	if err != nil || string(want) != got {
		t.Errorf("%s is stale; run UPDATE_GOLDEN=1 go test ./internal/mcp (read err: %v)", transcriptFile, err)
	}
}

func redact(a string) string {
	if a == "" {
		return "(none)"
	}
	return a
}
